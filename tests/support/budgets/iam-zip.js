// Fixed, small IAM JSON assets only. ZIP STORE, CRC32, central directory and
// EOCD per PKWARE APPNOTE 6.3.10; no compression library or external executable.
export function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++)
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
export function iamZip(assets) {
  const names = ['policies.json', 'users.json', 'user_mappings.json'];
  if (
    Object.keys(assets).length !== 3 ||
    names.some((name) => !Object.hasOwn(assets, name))
  )
    throw new Error('IAM_ASSETS_REQUIRED');
  const local = [],
    central = [];
  let offset = 0;
  for (const key of names) {
    const name = Buffer.from(`iam-assets/${key}`),
      data = Buffer.from(JSON.stringify(assets[key]));
    if (data.length > 1048576) throw new Error('IAM_ASSET_LIMIT');
    const crc = crc32(data),
      header = Buffer.alloc(30),
      entry = Buffer.alloc(46);
    header.writeUInt32LE(0x04034b50);
    header.writeUInt16LE(20, 4);
    header.writeUInt16LE(33, 12);
    header.writeUInt32LE(crc, 14);
    header.writeUInt32LE(data.length, 18);
    header.writeUInt32LE(data.length, 22);
    header.writeUInt16LE(name.length, 26);
    entry.writeUInt32LE(0x02014b50);
    entry.writeUInt16LE(20, 4);
    entry.writeUInt16LE(20, 6);
    entry.writeUInt16LE(33, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(data.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(name.length, 28);
    entry.writeUInt32LE(offset, 42);
    local.push(header, name, data);
    central.push(entry, name);
    offset += header.length + name.length + data.length;
  }
  const directory = Buffer.concat(central),
    end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50);
  end.writeUInt16LE(3, 8);
  end.writeUInt16LE(3, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, directory, end]);
}
